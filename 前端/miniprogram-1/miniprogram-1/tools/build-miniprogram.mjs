import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { spawnSync } from "node:child_process";

const root = process.cwd();
const dist = join(root, "dist");
const shouldBuild = process.argv.includes("--build");
const shouldCheck = shouldBuild || process.argv.includes("--check");

if (!shouldCheck) {
  throw new Error("Use --check or --build");
}

const excludedNames = new Set([
  ".git",
  ".gitignore",
  "dist",
  "node_modules",
  "package.json",
  "package-lock.json",
  "project.private.config.json",
  "tools"
]);

const requiredRootFiles = [
  "app.js",
  "app.json",
  "app.wxss",
  "config.js",
  "project.config.json",
  "sitemap.json"
];

for (const file of requiredRootFiles) {
  if (!existsSync(join(root, file))) {
    throw new Error(`Missing required mini program file: ${file}`);
  }
}

function walk(directory) {
  return readdirSync(directory)
    .filter((name) => !excludedNames.has(name))
    .flatMap((name) => {
      const absolute = join(directory, name);
      return statSync(absolute).isDirectory() ? walk(absolute) : [absolute];
    });
}

function parseJson(file) {
  try {
    return JSON.parse(readFileSync(file, "utf8"));
  } catch (error) {
    throw new Error(`Invalid JSON in ${relative(root, file)}: ${error.message}`);
  }
}

const sourceFiles = walk(root);
for (const file of sourceFiles.filter((item) => item.endsWith(".json"))) {
  parseJson(file);
}

for (const file of sourceFiles.filter((item) => item.endsWith(".js"))) {
  const result = spawnSync(process.execPath, ["--check", file], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`JavaScript syntax error in ${relative(root, file)}:\n${result.stderr}`);
  }
}

const appConfig = parseJson(join(root, "app.json"));
if (!Array.isArray(appConfig.pages) || appConfig.pages.length === 0) {
  throw new Error("app.json must declare at least one page");
}

for (const page of appConfig.pages) {
  for (const extension of ["js", "json", "wxml", "wxss"]) {
    const pageFile = join(root, `${page}.${extension}`);
    if (!existsSync(pageFile)) {
      throw new Error(`app.json references missing page file: ${page}.${extension}`);
    }
  }
}

const apiBaseUrl = process.env.MINIPROGRAM_API_BASE_URL || "http://127.0.0.1:8081";
let parsedApiUrl;
try {
  parsedApiUrl = new URL(apiBaseUrl);
} catch {
  throw new Error("MINIPROGRAM_API_BASE_URL must be an absolute http(s) URL");
}
if (!["http:", "https:"].includes(parsedApiUrl.protocol)) {
  throw new Error("MINIPROGRAM_API_BASE_URL must use http or https");
}

if (shouldBuild) {
  rmSync(dist, { recursive: true, force: true });
  mkdirSync(dist, { recursive: true });

  for (const source of sourceFiles) {
    const target = join(dist, relative(root, source));
    mkdirSync(dirname(target), { recursive: true });
    cpSync(source, target);
  }

  const runtimeConfig = `// Generated by npm run build. Do not edit the dist copy.\nconst config = ${JSON.stringify({
    baseUrl: apiBaseUrl.replace(/\/$/, ""),
    apis: {
      login: "/login",
      services: "/api/services",
      bindings: "/api/bindings",
      emergency: "/api/emergency"
    }
  }, null, 2)};\n\nmodule.exports = config;\n`;
  writeFileSync(join(dist, "config.js"), runtimeConfig, "utf8");

  const manifest = {
    generatedAt: new Date().toISOString(),
    apiBaseUrl: apiBaseUrl.replace(/\/$/, ""),
    pageCount: appConfig.pages.length,
    sourceFileCount: sourceFiles.length,
    excludedPrivateFiles: ["project.private.config.json"]
  };
  writeFileSync(join(dist, "build-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
}

console.log(`${shouldBuild ? "build" : "check"} passed: ${appConfig.pages.length} pages, ${sourceFiles.length} source files`);
